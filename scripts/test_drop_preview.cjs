const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require(process.argv[2] || 'typescript');
const source = fs.readFileSync('entry/src/main/ets/input/DropPreview.ets', 'utf8');
const code = ts.transpileModule(source, { reportDiagnostics: true, compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS } });
assert.equal((code.diagnostics || []).filter(d => d.category === ts.DiagnosticCategory.Error).length, 0);
const mod = { exports: {} };
vm.runInNewContext(code.outputText, { module: mod, exports: mod.exports });
const { DropPreview, localDropPoint } = mod.exports;
const point = localDropPoint(120, 90, 20, 30);
assert.equal(point.x, 100); assert.equal(point.y, 60);
assert.equal(localDropPoint(Infinity, 1, 0, 0), null);
assert.equal(localDropPoint(1, 1, NaN, 0), null);
const state = new DropPreview();
const seq = state.move();
const feedback = { sequence: seq, mode: 'place', left: 40, top: 100, width: 600, height: 400 };
state.apply(feedback, 2);
assert.equal(state.mode, 'place'); assert.equal(state.left, 20); assert.equal(state.height, 200);
state.move();
state.apply({ ...feedback, mode: 'open' }, 2);
assert.equal(state.mode, 'place', 'stale hover response ignored');
state.apply({ ...feedback, sequence: state.sequence, mode: 'open' }, 2);
assert.equal(state.mode, 'open', 'moving out of the canvas updates the action');
state.hide(); state.apply({ ...feedback, sequence: state.sequence }, 2);
assert.equal(state.visible, false); assert.equal(state.mode, '', 'late response cannot show overlay after leaving or dropping');
state.move();
state.apply({ ...feedback, sequence: state.sequence, mode: 'invalid' }, 2); assert.equal(state.mode, '');
state.apply({ ...feedback, sequence: state.sequence, width: NaN }, 2); assert.equal(state.mode, '');
state.apply({ ...feedback, sequence: state.sequence }, 0); assert.equal(state.mode, '');
state.sequence = 2147483647; assert.equal(state.move(), 1, 'native i32 sequence remains valid');
const page = fs.readFileSync('entry/src/main/ets/pages/Index.ets', 'utf8');
assert.match(page, /hitTestBehavior\(HitTestMode.None\)/, 'overlay must not intercept drops or native pointer input');
assert.match(page, /native\.drop\(image\.name, image\.bytes, x, y\)/);
assert.match(page, /native\.dropFile\(name, fd, x, y\)/);
assert.doesNotMatch(page, /导入为图层|打开为新文档|松开以导入|this\.dropPreview\.x|Circle\(/, 'drag text, floating hint and pointer marker are removed');
console.log('PASS: local coordinates, feedback scaling, switching targets, stale replies, leave/drop hiding, invalid feedback, and transparent hit testing.');
